def apply_specialty(products: list, meals: list) -> None:
    by_fr = {p["fr"]: p for p in products if "fr" in p}
    for fr, trans in SPECIALTY.items():
        if fr in by_fr:
            by_fr[fr].update(trans)
        else:
            products.append({"fr": fr, "en": trans.get("en", fr), **trans})
    by_id = {m["id"]: m for m in meals}
    for mid, labels in MEAL_LABELS.items():
        if mid in by_id:
            by_id[mid]["labels"].update(labels)


def strip_garbage_keys(data: dict) -> int:
    n = 0
    for key in list(GARBAGE_PROD_KEYS):
        if key in data:
            del data[key]
            n += 1
        meta = f"@{key}"
        if meta in data:
            del data[meta]
            n += 1
    return n
